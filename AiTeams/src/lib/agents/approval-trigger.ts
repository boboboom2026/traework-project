/**
 * 审批意图识别
 *
 * 用途：判断"用户指令"是否显式声明了需要人工审批。
 * 命中后由调用方（如 agent-chat 路由）向 system prompt 注入"审批模式"指令，
 * 引导智能体在产出后调用 submit_for_approval 提交待审。
 *
 * 设计原则：
 * - 只在"本条用户指令"上生效（per-instruction），不跨轮次持久化。
 * - 关键词尽量精准，避免"提到审批"就误触发；漏触发由 LLM 语义兜底。
 * - 容忍 Markdown 加粗（如 `需**我审批**`）、多余空白等书写差异。
 */

/** 审批触发规则（任一命中即视为需要审批） */
const APPROVAL_PATTERNS: RegExp[] = [
  // 需我审批 / 需要我确认 / 需我核准（此处"我"必需，避免"需要确认XX格式"这类误触发）
  /需(要)?[\s*_`]*我[\s*_`]*(审批|审核|批准|确认|核准|会签)/,
  // 需审批 / 需要审批 / 需审核 / 需报批（不含泛化的"确认"，降低误触发）
  /需(要)?[\s*_`]*(审批|审核|批准|核准|会签|报批)/,
  // 提交审批 / 提交给我审批 / 提交我审批 / 提交确认
  /提交(给)?[\s*_`]*我?[\s*_`]*(审批|审核|批准|确认)/,
  // 走审批 / 走一下审批 / 走个审批流程
  /走[\s*_`]*(一下|个|遍)?[\s*_`]*(审批|审核|报批)/,
  // 报我审批 / 向我报批 / 报批
  /(报|呈)[\s*_`]*(给)?[\s*_`]*我?[\s*_`]*(审批|批准|核准)|报批/,
  // 待我审批 / 待我确认 / 待我审核
  /待[\s*_`]*我[\s*_`]*(审批|审核|批准|确认)/,
  // 等我审批 / 等我确认 / 等我审核 / 等我同意
  /等[\s*_`]*我[\s*_`]*(审批|审核|批准|确认|同意)/,
  // 审批通过后 / 审核通过后再执行 / 批准后才开始
  /(审批|审核|批准|核准)[\s*_`]*(通过|后)[\s*_`]*(再|才|后)?[\s*_`]*(执行|继续|开始|落地|推进|实施)/,
  // 经我审批 / 由我审批 / 经我确认
  /(经|由)[\s*_`]*我[\s*_`]*(审批|审核|批准|确认)/,
];

/**
 * 判断给定文本是否包含审批意图。
 * @param text 用户指令原文
 */
export function detectApprovalIntent(text: string | undefined | null): boolean {
  if (!text) return false;
  const normalized = text.replace(/[*_`]/g, "").replace(/[ \t\u3000]+/g, " ");
  return APPROVAL_PATTERNS.some((re) => re.test(normalized));
}

/** 审批模式指令片段（命中后注入 system prompt） */
export const APPROVAL_MODE_PROMPT = [
  "",
  "## 审批模式（本条任务已声明需要人工审批）",
  "用户本次指令明确要求该任务需要人工审批。你必须遵循：",
  "1. 完成方案/产出物后，必须调用 submit_for_approval 工具将结果提交给用户确认，不得直接视为任务完成；",
  "2. 提交后在回复中向用户简要说明「已提交审批，请确认」，并展示待审内容摘要；",
  "3. 只有在收到用户审批通过（并可能附带下一步指示）后，才继续执行后续步骤。",
].join("\n");
